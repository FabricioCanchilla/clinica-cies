CREATE TABLE IF NOT EXISTS CAJA_DETALLE_PAGO (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 COD_PAG VARCHAR(10) NOT NULL UNIQUE,
 BASE DECIMAL(10,2) NOT NULL,
 PORCENTAJE SMALLINT NOT NULL,
 DESCUENTO DECIMAL(10,2) NOT NULL,
 COD_AUTORIZADOR VARCHAR(8) NULL,
 FOREIGN KEY (COD_PAG) REFERENCES PAGO(COD_PAG),
 FOREIGN KEY (COD_AUTORIZADOR) REFERENCES USUARIO(COD_USR)
) ENGINE=InnoDB;
