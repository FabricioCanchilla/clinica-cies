CREATE TABLE IF NOT EXISTS DIAGNOSTICO_CONSULTA (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 COD_CNS VARCHAR(10) NOT NULL,
 CODIGO VARCHAR(8) NOT NULL,
 DESCRIPCION VARCHAR(300) NOT NULL,
 FOREIGN KEY (COD_CNS) REFERENCES CONSULTA(COD_CNS),
 FOREIGN KEY (CODIGO) REFERENCES CATALOGO_CIE10(CODIGO)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ADENDA_EVOLUCION (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 COD_NEV VARCHAR(10) NOT NULL,
 COD_EMP VARCHAR(9) NOT NULL,
 FECHA DATETIME NOT NULL,
 TEXTO VARCHAR(500) NOT NULL,
 FOREIGN KEY (COD_NEV) REFERENCES NOTA_EVOLUCION(COD_NEV),
 FOREIGN KEY (COD_EMP) REFERENCES EMPLEADO(COD_EMP)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS INTERCONSULTA (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 COD_CNS VARCHAR(10) NOT NULL,
 COD_EMP VARCHAR(9) NOT NULL,
 MOTIVO VARCHAR(500) NOT NULL,
 PRIORIDAD VARCHAR(8) NOT NULL,
 FECHA DATETIME NOT NULL,
 ESTADO VARCHAR(12) NOT NULL DEFAULT 'Pendiente',
 RESPUESTA VARCHAR(500) NULL,
 RESPONDIDA DATETIME NULL,
 FOREIGN KEY (COD_CNS) REFERENCES CONSULTA(COD_CNS),
 FOREIGN KEY (COD_EMP) REFERENCES EMPLEADO(COD_EMP)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CONSENTIMIENTO_MEDICO (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 COD_CNS VARCHAR(10) NOT NULL,
 COD_EMP VARCHAR(9) NOT NULL,
 FECHA DATETIME NOT NULL,
 PROCEDIMIENTO VARCHAR(200) NOT NULL,
 INFORMACION TEXT NOT NULL,
 FIRMANTE VARCHAR(100) NOT NULL,
 CI_FIRMANTE VARCHAR(20) NOT NULL,
 FIRMA MEDIUMTEXT NOT NULL,
 FOREIGN KEY (COD_CNS) REFERENCES CONSULTA(COD_CNS),
 FOREIGN KEY (COD_EMP) REFERENCES EMPLEADO(COD_EMP)
) ENGINE=InnoDB;

