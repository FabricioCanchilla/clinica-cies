-- https://deis.minsal.cl/centrofic/ (Lista Tabular CIE-10). 12.548 códigos.
-- Se normalizan códigos sin punto, sin asterisco/daga; no se incluyen rangos ni encabezados.
CREATE TABLE IF NOT EXISTS MEDICO_ATENCION (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 COD_CIT VARCHAR(10) NOT NULL UNIQUE,
 ESTADO VARCHAR(15) NOT NULL,
 LLEGADA DATETIME NULL,
 INICIO DATETIME NULL,
 FOREIGN KEY (COD_CIT) REFERENCES CITA(COD_CIT)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CATALOGO_CIE10 (
 CODIGO VARCHAR(8) PRIMARY KEY,
 DESCRIPCION VARCHAR(300) NOT NULL
) ENGINE=InnoDB;
