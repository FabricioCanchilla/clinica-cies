CREATE TABLE IF NOT EXISTS SALDO_CREDITO (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 COD_PAC VARCHAR(10) NOT NULL,
 COD_CIT VARCHAR(10) NOT NULL UNIQUE,
 MONTO DECIMAL(10,2) NOT NULL,
 FECHA DATETIME NOT NULL,
 FOREIGN KEY (COD_PAC) REFERENCES PACIENTE(COD_PAC),
 FOREIGN KEY (COD_CIT) REFERENCES CITA(COD_CIT)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS SALDO_APLICACION (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 CREDITO_ID BIGINT UNSIGNED NOT NULL,
 COD_CIT VARCHAR(10) NOT NULL,
 MONTO DECIMAL(10,2) NOT NULL,
 FECHA DATETIME NOT NULL,
 UNIQUE (CREDITO_ID, COD_CIT),
 FOREIGN KEY (CREDITO_ID) REFERENCES SALDO_CREDITO(id),
 FOREIGN KEY (COD_CIT) REFERENCES CITA(COD_CIT)
) ENGINE=InnoDB;
