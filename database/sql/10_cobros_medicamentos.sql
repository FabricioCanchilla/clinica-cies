CREATE TABLE IF NOT EXISTS FARMACIA_PRECIO (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 COD_MED VARCHAR(8) NOT NULL,
 PRECIO DECIMAL(10,2) NOT NULL,
 FECHA DATETIME NOT NULL,
 COD_EMP VARCHAR(9) NOT NULL,
 FOREIGN KEY (COD_MED) REFERENCES MEDICAMENTO(COD_MED),
 FOREIGN KEY (COD_EMP) REFERENCES EMPLEADO(COD_EMP)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CAJA_MEDICAMENTO (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 COD_CME VARCHAR(10) NOT NULL UNIQUE,
 COD_PAC VARCHAR(10) NOT NULL,
 COD_MED VARCHAR(8) NOT NULL,
 COD_DRE VARCHAR(10) NOT NULL,
 COD_CAJ VARCHAR(10) NOT NULL,
 COD_MET VARCHAR(7) NOT NULL,
 CANTIDAD INT NOT NULL,
 PRECIO DECIMAL(10,2) NOT NULL,
 MONTO DECIMAL(10,2) NOT NULL,
 FECHA DATETIME NOT NULL,
 ESTADO VARCHAR(10) NOT NULL,
 FOREIGN KEY (COD_PAC) REFERENCES PACIENTE(COD_PAC),
 FOREIGN KEY (COD_MED) REFERENCES MEDICAMENTO(COD_MED),
 FOREIGN KEY (COD_DRE) REFERENCES DETALLE_RECETA(COD_DRE),
 FOREIGN KEY (COD_CAJ) REFERENCES CAJA(COD_CAJ),
 FOREIGN KEY (COD_MET) REFERENCES METODO_PAGO(COD_MET)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CAJA_MEDICAMENTO_LOTE (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 COD_CME VARCHAR(10) NOT NULL,
 COD_LOT VARCHAR(10) NOT NULL,
 CANTIDAD INT NOT NULL,
 FOREIGN KEY (COD_CME) REFERENCES CAJA_MEDICAMENTO(COD_CME),
 FOREIGN KEY (COD_LOT) REFERENCES LOTE_MEDICAMENTO(COD_LOT)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CAJA_MEDICAMENTO_ANULACION (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 COD_CME VARCHAR(10) NOT NULL UNIQUE,
 COD_EMP VARCHAR(9) NOT NULL,
 FECHA DATETIME NOT NULL,
 MOTIVO VARCHAR(200) NOT NULL,
 FOREIGN KEY (COD_CME) REFERENCES CAJA_MEDICAMENTO(COD_CME),
 FOREIGN KEY (COD_EMP) REFERENCES EMPLEADO(COD_EMP)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CAJA_MEDICAMENTO_SOLICITUD (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 TOKEN VARCHAR(36) NOT NULL UNIQUE,
 COD_CME VARCHAR(10) NOT NULL UNIQUE,
 FOREIGN KEY (COD_CME) REFERENCES CAJA_MEDICAMENTO(COD_CME)
) ENGINE=InnoDB;
