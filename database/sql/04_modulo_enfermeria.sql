CREATE TABLE IF NOT EXISTS ENFERMERIA_NOTA (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 COD_INT VARCHAR(10) NOT NULL, COD_EMP VARCHAR(9) NOT NULL,
 FECHA DATETIME NOT NULL, TEXTO VARCHAR(500) NOT NULL,
 FOREIGN KEY (COD_INT) REFERENCES INTERNACION(COD_INT),
 FOREIGN KEY (COD_EMP) REFERENCES EMPLEADO(COD_EMP)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ENFERMERIA_BALANCE (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 COD_INT VARCHAR(10) NOT NULL, COD_EMP VARCHAR(9) NOT NULL,
 FECHA DATETIME NOT NULL, INGRESO DECIMAL(9,2) NOT NULL,
 EGRESO DECIMAL(9,2) NOT NULL, OBSERVACION VARCHAR(250) NULL,
 FOREIGN KEY (COD_INT) REFERENCES INTERNACION(COD_INT),
 FOREIGN KEY (COD_EMP) REFERENCES EMPLEADO(COD_EMP)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ENFERMERIA_FIRMA_DOSIS (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 COD_DOS VARCHAR(10) NOT NULL UNIQUE, FIRMA MEDIUMTEXT NOT NULL,
 FOREIGN KEY (COD_DOS) REFERENCES DOSIS(COD_DOS)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ENFERMERIA_CIERRE_INSUMO (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 COD_INS VARCHAR(10) NOT NULL UNIQUE, COD_EMP VARCHAR(9) NOT NULL,
 FECHA DATETIME NOT NULL, TIPO VARCHAR(12) NOT NULL,
 CANTIDAD SMALLINT NOT NULL, DETALLE VARCHAR(250) NOT NULL,
 FOREIGN KEY (COD_INS) REFERENCES INSUMO_TERCERO(COD_INS),
 FOREIGN KEY (COD_EMP) REFERENCES EMPLEADO(COD_EMP)
) ENGINE=InnoDB;
