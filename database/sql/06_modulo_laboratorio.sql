CREATE TABLE IF NOT EXISTS LAB_MUESTRA (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 COD_ORD VARCHAR(10) NOT NULL UNIQUE,
 TIPO VARCHAR(80) NOT NULL,
 FECHA DATETIME NOT NULL,
 COD_EMP VARCHAR(9) NOT NULL,
 FOREIGN KEY (COD_ORD) REFERENCES ORDEN_EXAMEN(COD_ORD),
 FOREIGN KEY (COD_EMP) REFERENCES EMPLEADO(COD_EMP)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS LAB_VALIDACION (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 COD_RES VARCHAR(10) NOT NULL UNIQUE,
 FECHA DATETIME NOT NULL,
 COD_EMP VARCHAR(9) NOT NULL,
 FOREIGN KEY (COD_RES) REFERENCES RESULTADO_EXAMEN(COD_RES),
 FOREIGN KEY (COD_EMP) REFERENCES EMPLEADO(COD_EMP)
) ENGINE=InnoDB;
