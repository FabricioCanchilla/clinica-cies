CREATE TABLE USUARIO (
  id         BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  COD_USR    VARCHAR(8)   NOT NULL,
  USR_USR    VARCHAR(20)  NOT NULL,
  CON_USR    VARCHAR(255) NOT NULL,
  EST_USR    VARCHAR(10)  NOT NULL DEFAULT 'Activo',
  INTFAL_USR TINYINT UNSIGNED NOT NULL DEFAULT 0,
  CAMCON_USR TINYINT UNSIGNED NOT NULL DEFAULT 0,
  FECULT_USR DATETIME     NULL,
  FECREG_USR DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  COD_ROL    VARCHAR(6)   NOT NULL,
  COD_EMP    VARCHAR(9)   NULL,
  COD_PAC    VARCHAR(10)  NULL,
  PRIMARY KEY (id),
  UNIQUE KEY UQ_USUARIO_COD (COD_USR),
  UNIQUE KEY UQ_USUARIO_USR (USR_USR),
  CONSTRAINT CK_USUARIO_EST     CHECK (EST_USR IN ('Activo','Inactivo','Bloqueado')),
  CONSTRAINT CK_USUARIO_TITULAR CHECK ((COD_EMP IS NULL) <> (COD_PAC IS NULL)),
  CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (COD_ROL) REFERENCES ROL(COD_ROL),
  CONSTRAINT FK_USUARIO_EMP FOREIGN KEY (COD_EMP) REFERENCES EMPLEADO(COD_EMP),
  CONSTRAINT FK_USUARIO_PAC FOREIGN KEY (COD_PAC) REFERENCES PACIENTE(COD_PAC)
) ENGINE=InnoDB;

CREATE TABLE OTP (
  id         BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  COD_OTP    VARCHAR(10)  NOT NULL,
  VAL_OTP    VARCHAR(255) NOT NULL,
  PRO_OTP    VARCHAR(20)  NOT NULL,
  CAN_OTP    VARCHAR(6)   NOT NULL,           -- canal: Correo o SMS
  DST_OTP    VARCHAR(60)  NOT NULL,           -- correo o teléfono de destino
  FECEMI_OTP DATETIME     NOT NULL,
  FECEXP_OTP DATETIME     NOT NULL,
  EST_OTP    VARCHAR(10)  NOT NULL,
  INT_OTP    TINYINT UNSIGNED NOT NULL DEFAULT 0,
  COD_USR    VARCHAR(8)   NULL,
  PRIMARY KEY (id),
  UNIQUE KEY UQ_OTP_COD (COD_OTP),
  CONSTRAINT CK_OTP_CAN CHECK (CAN_OTP IN ('Correo','SMS')),
  CONSTRAINT CK_OTP_EST CHECK (EST_OTP IN ('Pendiente','Verificado','Expirado','Bloqueado')),
  CONSTRAINT CK_OTP_FEC CHECK (FECEXP_OTP > FECEMI_OTP),
  CONSTRAINT FK_OTP_USR FOREIGN KEY (COD_USR) REFERENCES USUARIO(COD_USR)
) ENGINE=InnoDB;

