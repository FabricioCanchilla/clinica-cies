  CONSTRAINT FK_CITA_CON FOREIGN KEY (COD_CON) REFERENCES CONSULTORIO(COD_CON),
  CONSTRAINT FK_CITA_SRV FOREIGN KEY (COD_SRV) REFERENCES SERVICIO(COD_SRV)
) ENGINE=InnoDB;

