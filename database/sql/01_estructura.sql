CREATE TABLE CAJA (
  id         BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  COD_CAJ    VARCHAR(10)   NOT NULL,
  FECAPE_CAJ DATETIME      NOT NULL,
  MONAPE_CAJ DECIMAL(10,2) NOT NULL,
  FECCIE_CAJ DATETIME      NULL,
  MONCIE_CAJ DECIMAL(10,2) NULL,
  EST_CAJ    VARCHAR(8)    NOT NULL,
  COD_EMP    VARCHAR(9)    NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY UQ_CAJA_COD (COD_CAJ),
  CONSTRAINT CK_CAJA_EST   CHECK (EST_CAJ IN ('Abierta','Cerrada')),
  CONSTRAINT CK_CAJA_MONAP CHECK (MONAPE_CAJ >= 0),
  CONSTRAINT CK_CAJA_MONCI CHECK (MONCIE_CAJ IS NULL OR MONCIE_CAJ >= 0),
  CONSTRAINT CK_CAJA_CIERRE CHECK ((FECCIE_CAJ IS NULL) = (MONCIE_CAJ IS NULL)),
  CONSTRAINT CK_CAJA_FEC   CHECK (FECCIE_CAJ IS NULL OR FECCIE_CAJ >= FECAPE_CAJ),
  CONSTRAINT FK_CAJA_EMP FOREIGN KEY (COD_EMP) REFERENCES EMPLEADO(COD_EMP)
) ENGINE=InnoDB;

CREATE TABLE CITA (
  id         BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  COD_CIT    VARCHAR(10)  NOT NULL,
  FEC_CIT    DATE         NOT NULL,
  HOR_CIT    TIME         NOT NULL,
  DUR_CIT    SMALLINT     NOT NULL,
  EST_CIT    VARCHAR(20)  NOT NULL,
  MOT_CIT    VARCHAR(200) NOT NULL,
  FECEXP_CIT DATETIME     NULL,
  COD_PAC    VARCHAR(10)  NOT NULL,
  COD_EMP    VARCHAR(9)   NOT NULL,
  COD_CON    VARCHAR(6)   NOT NULL,
  COD_SRV    VARCHAR(8)   NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY UQ_CITA_COD (COD_CIT),
  CONSTRAINT CK_CITA_DUR CHECK (DUR_CIT > 0),
  CONSTRAINT CK_CITA_EST CHECK (EST_CIT IN ('Pendiente de pago','Confirmada','Atendida','Cancelada','Expirada','No asistio')),
