-- =====================================================================
-- CLÍNICA CIES — Script MySQL v2 (47 tablas)
-- Llaves: combinación 2
--   * Cada tabla lleva `id` BIGINT UNSIGNED AUTO_INCREMENT como PK técnica
--   * Además lleva su código del diccionario (COD_xxx / NRO_xxx), UNIQUE
--   * Las llaves foráneas apuntan al CÓDIGO, no al id
--   * Excepción: ROL_PERMISO es tabla pivote (PK compuesta, sin id)
-- Cambios respecto a v1:
--   * ENTREGANTE: + TEL_ENT (SMS para OTP de familiares)
--   * OTP: + CAN_OTP (Correo/SMS) y CORDES_OTP pasa a DST_OTP (correo o teléfono)
--   * RESULTADO_EXAMEN: + COD_EMP (quién carga el resultado)
--   * CHECKs de sexo, estados, rangos y fechas
-- Requiere MySQL 8.0.16+ (antes ignora los CHECK)
-- =====================================================================
SET NAMES utf8mb4;
CREATE DATABASE IF NOT EXISTS clinica_cies
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
